    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
    if (indice < asistentes.length) {
        String nombre = txtNombre.getText().trim();

    if (nombre.isEmpty()) {
        JOptionPane.showMessageDialog(this,
        "Escribe el nombre del asistente.");
        return;
    }

    asistentes[indice] = nombre;
    indice++;

    txtLista.append(indice + ". " + nombre + "\n");
    txtNombre.setText("");
    txtNombre.requestFocus();

    JOptionPane.showMessageDialog(this,
            "Asistente registrado correctamente.");

} else {
    JOptionPane.showMessageDialog(this,
            "Ya registraste los 5 asistentes.");
}
   
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        // TODO add your handling code here:
    
    if (indice == 0) {
    JOptionPane.showMessageDialog(this,
            "Primero debes registrar a los asistentes.");
    return;
    }

    try {
    java.io.File carpeta = new java.io.File("temp");
    carpeta.mkdirs();

    java.io.FileWriter archivo =
        new java.io.FileWriter("temp/asistencia.txt");

    archivo.write("Lista de Asistencia\n");

    for (int i = 0; i < indice; i++) {
        archivo.write((i + 1) + ". " + asistentes[i] + "\n");
    }

    archivo.close();

    JOptionPane.showMessageDialog(this,
        "Lista exportada correctamente en temp/asistencia.txt");

    } catch (java.io.IOException e) {
    JOptionPane.showMessageDialog(this,
        "Error al exportar la lista: " + e.getMessage());
    }

    }//GEN-LAST:event_btnExportarActionPerformed

