    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
    String albumBuscado = txtAlbum.getText().trim();
String nuevoAnioTexto = txtNuevoAnio.getText().trim();

if (albumBuscado.isEmpty() || nuevoAnioTexto.isEmpty()) {
    JOptionPane.showMessageDialog(
        this,
        "Ingresa el nombre del álbum y el nuevo año."
    );
    return;
}

int nuevoAnio;

try {
    nuevoAnio = Integer.parseInt(nuevoAnioTexto);

    if (nuevoAnio <= 0) {
        JOptionPane.showMessageDialog(
            this,
            "El año debe ser un número positivo."
        );
        return;
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(
        this,
        "El año debe ser un número entero."
    );
    return;
}

int posicion = -1;

for (int i = 0; i < cantidad; i++) {
    if (titulos[i].equalsIgnoreCase(albumBuscado)) {
        posicion = i;
        break;
    }
}

if (posicion == -1) {
    JOptionPane.showMessageDialog(
        this,
        "Primero busca un álbum que exista."
    );
    return;
}

try (PrintWriter escritor =
        new PrintWriter(new FileWriter("temp/discos.csv", false))) {

    escritor.println("Album,Anio");

    for (int i = 0; i < cantidad; i++) {
        if (i == posicion) {
            anios[i] = nuevoAnio;
        }

        escritor.println(titulos[i] + "," + anios[i]);
    }

    lblAnio.setText(String.valueOf(nuevoAnio));
    txtNuevoAnio.setText("");

    JOptionPane.showMessageDialog(
        this,
        "El año del álbum se actualizó correctamente."
    );

} catch (Exception e) {
    JOptionPane.showMessageDialog(
        this,
        "Error al guardar los cambios: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnActualizarActionPerformed

