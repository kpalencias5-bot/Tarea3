    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        // TODO add your handling code here:
    
if (cantidad == 0) {
    JOptionPane.showMessageDialog(this,
            "Primero debes cargar las temperaturas.");
    return;
}

double suma = 0;
int calidos = 0;
int frescos = 0;

for (int i = 0; i < cantidad; i++) {
    suma += temperaturas[i];

    if (temperaturas[i] >= 25) {
        calidos++;
    } else {
        frescos++;
    }
}

double promedio = suma / cantidad;

txtResultados.append("\n--- Estadísticas ---\n");
txtResultados.append("Promedio: "
        + String.format("%.2f", promedio) + " °C\n");
txtResultados.append("Días cálidos: " + calidos + "\n");
txtResultados.append("Días frescos: " + frescos + "\n");
   
    }//GEN-LAST:event_btnCalcularActionPerformed

    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
        // TODO add your handling code here:
        
cantidad = 0;
txtResultados.setText("");

try {
    java.io.BufferedReader lector =
        new java.io.BufferedReader(
        new java.io.FileReader("temp/temperaturas.txt"));

    String linea;

    while ((linea = lector.readLine()) != null
            && cantidad < temperaturas.length) {

        if (!linea.trim().isEmpty()) {
            temperaturas[cantidad] =
            Double.parseDouble(linea.trim());
            cantidad++;
        }
    }

    lector.close();

    txtResultados.setText("Temperaturas cargadas:\n");

    for (int i = 0; i < cantidad; i++) {
        txtResultados.append(
        (i + 1) + ". " + temperaturas[i] + " °C\n");
    }

    JOptionPane.showMessageDialog(this,
    "Datos cargados correctamente.");

} catch (java.io.IOException | NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
    "Error al leer el archivo: " + e.getMessage());
}

        
    }//GEN-LAST:event_btnCargarActionPerformed

