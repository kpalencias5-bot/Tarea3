    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
        // TODO add your handling code here:
    
String nombre = txtNombreArtista.getText().trim();
String pais = txtPaisOrigen.getText().trim();
String oyentesTexto = txtOyentes.getText().trim();

if (nombre.isEmpty() || pais.isEmpty() || oyentesTexto.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Completa todos los datos del artista."
    );
    return;
}

int oyentes;

try {
    oyentes = Integer.parseInt(oyentesTexto);

    if (oyentes < 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Los oyentes no pueden ser negativos."
        );
        return;
    }
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Los oyentes mensuales deben ser un número entero."
    );
    return;
}

Artista artista = new Artista();

artista.nombre = nombre;
artista.paisOrigen = pais;
artista.oyentesMensuales = oyentes;

txtResultados.append("=== ARTISTA ===\n");
txtResultados.append("Nombre: " + artista.nombre + "\n");
txtResultados.append("País de origen: " + artista.paisOrigen + "\n");
txtResultados.append("Oyentes mensuales: " + artista.oyentesMensuales + "\n\n");

    }//GEN-LAST:event_btnCrearArtistaActionPerformed

    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
        // TODO add your handling code here:
    
String titulo = txtTituloCancion.getText().trim();
String duracionTexto = txtDuracion.getText().trim();
String genero = txtGenero.getText().trim();
String nombreArtista = txtNombreArtistaCancion.getText().trim();

// Validar que todos los campos estén completos
if (titulo.isEmpty() || duracionTexto.isEmpty()
        || genero.isEmpty() || nombreArtista.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
        this, "Completa todos los datos de la canción."
    );
    return;
}

// Validar la duración
int duracion;

try {
    duracion = Integer.parseInt(duracionTexto);

    if (duracion <= 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "La duración debe ser mayor que cero."
        );
        return;
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "La duración debe ser un número entero."
    );
    return;
}

// Crear el objeto Cancion
Cancion cancion = new Cancion();

cancion.titulo = titulo;
cancion.duracionSegundos = duracion;
cancion.genero = genero;
cancion.nombreArtista = nombreArtista;

// Mostrar los datos en el área de resultados
txtResultados.append("=== CANCIÓN ===\n");
txtResultados.append("Título: " + cancion.titulo + "\n");
txtResultados.append("Duración: "
        + cancion.duracionSegundos + " segundos\n");
txtResultados.append("Género: " + cancion.genero + "\n");
txtResultados.append("Artista: " + cancion.nombreArtista + "\n\n");

    }//GEN-LAST:event_btnCrearCancionActionPerformed

