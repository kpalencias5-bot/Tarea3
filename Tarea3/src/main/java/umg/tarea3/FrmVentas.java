    private void btnAgregarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarVentaActionPerformed
        // TODO add your handling code here:
    if (indice < ventas.length) {
        try {
            double monto = Double.parseDouble(txtMonto.getText());
            if (monto < 0){
                JOptionPane.showMessageDialog(this,
                    "El monto no puede ser negativo.");
            return;
            }
            ventas[indice] = monto;
            indice++;
            JOptionPane.showMessageDialog(this,
                "Venta agregada correctamente.");

        txtMonto.setText("");
        txtMonto.requestFocus();
        
        } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Ingresa un monto numérico válido.");
        }
    } else {
    JOptionPane.showMessageDialog(this,
            "Ya registraste las 5 ventas.");
    }     
    }//GEN-LAST:event_btnAgregarVentaActionPerformed

    private void btnGenerarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarReporteActionPerformed
        // TODO add your handling code here:
        if (indice < 5) {
            JOptionPane.showMessageDialog(this,
                "Debes registrar las 5 ventas antes de generar el reporte.");
            return;
        }
        double total = 0;
        int superiores = 0;
        
        for (int i = 0; i < ventas.length; i++) {
            total += ventas[i];
            
            if (ventas[i] > 500) {
                superiores++;
            }
        }
    try {
    java.io.File carpeta = new java.io.File("temp");
    carpeta.mkdirs();
    
    java.io.FileWriter archivo =
        new java.io.FileWriter("temp/reporte_ventas.txt");

    archivo.write("Reporte de Ventas\n");
    archivo.write("Total Vendido: Q" + total + "\n");
    archivo.write("Ventas superiores a Q500: " + superiores + "\n");

    archivo.close();

    JOptionPane.showMessageDialog(this,
            "Reporte generado correctamente en temp/reporte_ventas.txt");
} catch (java.io.IOException e) {
    JOptionPane.showMessageDialog(this,
            "Error al guardar el reporte: " + e.getMessage());
}
            
    }//GEN-LAST:event_btnGenerarReporteActionPerformed

