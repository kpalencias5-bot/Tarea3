    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        // TODO add your handling code here:
    
txtResultados.setText("");

if (videojuegos.isEmpty()) {
    txtResultados.setText("No hay videojuegos registrados.");
    return;
}

txtResultados.append("=== LISTA DE VIDEOJUEGOS ===\n\n");

for (int i = 0; i < videojuegos.size(); i++) {
    txtResultados.append(
            (i + 1) + ". " + videojuegos.get(i).toString() + "\n\n"
    );
}

    }//GEN-LAST:event_btnMostrarActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
    
String nombre = txtNombre.getText().trim();
String plataforma = txtPlataforma.getText().trim();
String anioTexto = txtAnio.getText().trim();

if (nombre.isEmpty() || plataforma.isEmpty()
        || anioTexto.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Completa todos los campos.");
    return;
}

int anio;

try {
    anio = Integer.parseInt(anioTexto);
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "El año debe ser un número entero.");
    return;
}

if (anio <= 0) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Ingresa un año válido.");
    return;
}

Videojuego videojuego =
        new Videojuego(nombre, plataforma, anio);

videojuegos.add(videojuego);

javax.swing.JOptionPane.showMessageDialog(
        this, "Videojuego agregado correctamente.");

txtNombre.setText("");
txtPlataforma.setText("");
txtAnio.setText("");
txtNombre.requestFocus();

    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
    
if (videojuegos.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "No hay videojuegos para eliminar.");
    return;
}

Videojuego eliminado = videojuegos.remove(
        videojuegos.size() - 1);

javax.swing.JOptionPane.showMessageDialog(
        this, "Se eliminó el videojuego: "
        + eliminado.nombre);

txtResultados.setText("");

if (videojuegos.isEmpty()) {
    txtResultados.setText(
            "No hay videojuegos registrados.");
} else {
    txtResultados.append("=== LISTA DE VIDEOJUEGOS ===\n\n");

    for (int i = 0; i < videojuegos.size(); i++) {
        txtResultados.append(
                (i + 1) + ". "
                + videojuegos.get(i).toString() + "\n\n");
    }
}

    }//GEN-LAST:event_btnEliminarActionPerformed

